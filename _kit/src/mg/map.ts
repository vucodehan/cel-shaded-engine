/**
 * Maps in the house motion-design style: coasts drawn on in gold line art over a
 * dark ink ground, dark land, routes drawing on in gold, Cinzel place names with a dark edge, a warm light spreading
 * over the land. One Canvas2D drawing (drawMap) serves both uses:
 *   - a full-frame 2D insert inside a cel film (MapInsert.tsx), palette "gold";
 *   - a texture on a 3D prop, a map on a table, wall or scroll (mapTexture.ts), palette "ink" (brown ink on parchment).
 *
 * Coordinates are [lon, lat]. A view is { lon, lat, span }: span = degrees of latitude across the SHORT side of the
 * frame, so one view frames 16:9 and 9:16 (portrait shows more north-south), like the cel shot sizes. Longitude is
 * scaled by cos(refLat) (default 34°). Close views (span <= 5) inside Egypt's delta..Damascus use the detailed ne_10m
 * coastline; everything else uses ne_50m (geo-data.ts, generated by _tools/mapdata.py).
 */
import { BOX_H, COAST_H, COAST_M, LAKES, LAND_H, LAND_M, RIVERS } from "./geo-data";
import { LL, PLACES, PlaceKind, placeLL } from "./places";
import { MAP_FONT } from "./fonts";

export type MapView = { lon: number; lat: number; span: number };
export type Route = {
  via: (string | LL)[];
  /** draw-on progress 0..1 */
  p: number;
  /** dashed, dim: a route to come or a road not taken */
  faint?: boolean;
  /** smooth through the points (Catmull-Rom) instead of straight legs */
  smooth?: boolean;
  width?: number;
  color?: string;
  /** arrowhead at the drawing tip */
  arrow?: boolean;
};
export type Pin = {
  at: string | LL;
  /** 0..1 fade/pop */
  a: number;
  /** label text; default the place's name; false = pin only */
  label?: string | false;
  dx?: number;
  dy?: number;
  big?: boolean;
  /** override the place's kind (region and sea labels draw without a pin) */
  kind?: PlaceKind;
};
export type MapSpec = {
  view: MapView;
  refLat?: number;
  /** coasts, lakes and rivers draw on 0..1 */
  draw?: number;
  /** land fill 0..1 (default min(1, draw * 1.6)) */
  land?: number;
  /** rivers draw-on 0..1 (default draw); riverNames limits which rivers draw (e.g. ["Jordan"]) */
  rivers?: number;
  riverNames?: string[];
  routes?: Route[];
  pins?: Pin[];
  /** warm light over the land around `at`; r = radius as a fraction of the frame diagonal (0..1.5) */
  light?: { at: string | LL; r: number };
  /** traveller marker (pulsing point), e.g. at routePoint(route, p) */
  head?: { at: string | LL; a: number };
  palette?: "gold" | "ink";
  /** paint the ground (default true for gold; ink maps leave it transparent for the parchment underneath) */
  ground?: boolean;
  /** line and text scale; default min(W, H) / 1080 */
  scale?: number;
  /** frame number, for the marker pulse */
  frame?: number;
};

type Palette = {
  ground: [string, string, string] | null; land: string; coast: string; glow: string; lake: string; river: string; route: string;
  faint: string; pin: string; ring: string; label: string; edge: string | null; region: string; sea: string; light: [string, string, string];
};

