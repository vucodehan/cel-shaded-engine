const D2R = Math.PI / 180;
const clamp01 = (x: number) => Math.max(0, Math.min(1, x));

export type Projector = { xy: (ll: LL) => [number, number]; pxPerDeg: number; W: number; H: number; hi: boolean };

export function projector(spec: MapSpec, W: number, H: number): Projector {
  const v = spec.view;
  const pxPerDeg = Math.min(W, H) / v.span;
  const k = Math.cos((spec.refLat ?? 34) * D2R);
  const [x0, y0, x1, y1] = BOX_H;
  const hi = v.span <= 5 && v.lon > x0 && v.lon < x1 && v.lat > y0 && v.lat < y1;
  return { xy: (ll) => [W / 2 + (ll[0] - v.lon) * k * pxPerDeg, H / 2 - (ll[1] - v.lat) * pxPerDeg], pxPerDeg, W, H, hi };
}

/** View that fits the given places (margin = fraction of the frame kept free on each side). */
export function fitView(at: (string | LL)[], W: number, H: number, margin = 0.12, refLat = 34): MapView {
  const pts = at.map(placeLL);
  const lo0 = Math.min(...pts.map((q) => q[0])), lo1 = Math.max(...pts.map((q) => q[0]));
  const la0 = Math.min(...pts.map((q) => q[1])), la1 = Math.max(...pts.map((q) => q[1]));
  const k = Math.cos(refLat * D2R);
  const ppd = Math.min((W * (1 - 2 * margin)) / Math.max((lo1 - lo0) * k, 0.05), (H * (1 - 2 * margin)) / Math.max(la1 - la0, 0.05));
  return { lon: (lo0 + lo1) / 2, lat: (la0 + la1) / 2, span: Math.min(W, H) / ppd };
}

/** Camera between view keys [frame, view]: smooth position, span interpolated in log space (constant zoom speed). */
export function mapCam(keys: [number, MapView][], f: number): MapView {
  if (f <= keys[0][0]) return keys[0][1];
  for (let i = 1; i < keys.length; i++) {
    const [fa, a] = keys[i - 1];
    const [fb, b] = keys[i];
    if (f <= fb) {
      const t = (f - fa) / Math.max(1, fb - fa);
      const e = t * t * (3 - 2 * t);
      return { lon: a.lon + (b.lon - a.lon) * e, lat: a.lat + (b.lat - a.lat) * e, span: Math.exp(Math.log(a.span) + (Math.log(b.span) - Math.log(a.span)) * e) };
    }
  }
  return keys[keys.length - 1][1];
}

// ---- polylines ----------------------------------------------------------------------------------------------

const lens = new WeakMap<object, number[]>();
/** Cumulative lengths (in degrees) of a flat [lon, lat, ...] array, cached. */
function cum(pts: number[]): number[] {
  let c = lens.get(pts);
  if (!c) {
    c = [0];
    for (let i = 2; i < pts.length; i += 2) c.push(c[c.length - 1] + Math.hypot(pts[i] - pts[i - 2], pts[i + 1] - pts[i - 1]));
    lens.set(pts, c);
  }
  return c;
}

function flatOf(via: (string | LL)[], smooth: boolean): number[] {
  const pts = via.map(placeLL);
  if (!smooth || pts.length < 3) return pts.flat();
  const out: number[] = [];
  for (let i = 0; i < pts.length - 1; i++) {
    const p0 = pts[Math.max(0, i - 1)], p1 = pts[i], p2 = pts[i + 1], p3 = pts[Math.min(pts.length - 1, i + 2)];
    for (let s = 0; s < 12; s++) {
      const t = s / 12, t2 = t * t, t3 = t2 * t;
      const c = (a: number, b: number, cc: number, d: number) => 0.5 * (2 * b + (-a + cc) * t + (2 * a - 5 * b + 4 * cc - d) * t2 + (-a + 3 * b - 3 * cc + d) * t3);
      out.push(c(p0[0], p1[0], p2[0], p3[0]), c(p0[1], p1[1], p2[1], p3[1]));
    }
  }
  out.push(...pts[pts.length - 1]);
  return out;
}

const routeCache = new Map<string, number[]>();
function routeFlat(r: { via: (string | LL)[]; smooth?: boolean }): number[] {
  const key = JSON.stringify([r.via, !!r.smooth]);
  let f = routeCache.get(key);
  if (!f) {
    f = flatOf(r.via, !!r.smooth);
    routeCache.set(key, f);
  }
  return f;
}

/** The point at fraction p (0..1) along a route, for a moving marker or a camera that follows. */
export function routePoint(r: { via: (string | LL)[]; smooth?: boolean }, p: number): LL {
  const pts = routeFlat(r);
  const c = cum(pts);
  const target = clamp01(p) * c[c.length - 1];
  for (let i = 1; i < c.length; i++) {
    if (c[i] >= target) {
      const t = (target - c[i - 1]) / Math.max(1e-9, c[i] - c[i - 1]);
      return [pts[2 * i - 2] + (pts[2 * i] - pts[2 * i - 2]) * t, pts[2 * i - 1] + (pts[2 * i + 1] - pts[2 * i - 1]) * t];
    }
  }
  return [pts[pts.length - 2], pts[pts.length - 1]];
}

/** Trace the first fraction p of a polyline; `skip` drops segments (detailed-area overlap). Returns the tip and heading. */
function trace(ctx: CanvasRenderingContext2D, pts: number[], pr: Projector, p: number, skip?: (lon: number, lat: number) => boolean) {
  const c = cum(pts);
  const stop = clamp01(p) * c[c.length - 1];
  let pen = false;
  let tip: [number, number] | null = null;
  let ang = 0;
  for (let i = 0; i < pts.length / 2; i++) {
    let lon = pts[2 * i], lat = pts[2 * i + 1];
    if (c[i] > stop) {
      if (i === 0) break;
      const t = (stop - c[i - 1]) / Math.max(1e-9, c[i] - c[i - 1]);
      lon = pts[2 * i - 2] + (lon - pts[2 * i - 2]) * t;
      lat = pts[2 * i - 1] + (lat - pts[2 * i - 1]) * t;
    }
    const drop = skip && i > 0 && skip(lon, lat) && skip(pts[2 * i - 2], pts[2 * i - 1]);
    const [x, y] = pr.xy([lon, lat]);
    if (!pen || drop) ctx.moveTo(x, y);
    else ctx.lineTo(x, y);
    if (tip) ang = Math.atan2(y - tip[1], x - tip[0]);
    tip = [x, y];
    pen = true;
    if (c[i] > stop) break;
  }
  return { tip, ang };
}

function ringPath(path: Path2D, pts: number[], pr: Projector) {
  for (let i = 0; i < pts.length; i += 2) {
    const [x, y] = pr.xy([pts[i], pts[i + 1]]);
    if (i === 0) path.moveTo(x, y);
    else path.lineTo(x, y);
  }
  path.closePath();
}

function inBox(lon: number, lat: number) {
  return lon > BOX_H[0] && lon < BOX_H[2] && lat > BOX_H[1] && lat < BOX_H[3];
}

function landPath(pr: Projector): { m: Path2D; h: Path2D | null; box: Path2D | null } {
  const m = new Path2D();
  LAND_M.forEach((r) => ringPath(m, r, pr));
  if (!pr.hi) return { m, h: null, box: null };
  const h = new Path2D();
  LAND_H.forEach((r) => ringPath(h, r, pr));
  const box = new Path2D();
  ringPath(box, [BOX_H[0], BOX_H[1], BOX_H[2], BOX_H[1], BOX_H[2], BOX_H[3], BOX_H[0], BOX_H[3]], pr);
  return { m, h, box };
}

function fillLand(ctx: CanvasRenderingContext2D, lp: ReturnType<typeof landPath>, W: number, H: number, style: string | CanvasGradient) {
  ctx.fillStyle = style;
  if (!lp.h || !lp.box) {
    ctx.fill(lp.m, "evenodd");
    return;
  }
  ctx.save();
  const outside = new Path2D();
  outside.rect(-W, -H, W * 3, H * 3);
  outside.addPath(lp.box);
  ctx.clip(outside, "evenodd");
  ctx.fill(lp.m, "evenodd");
  ctx.restore();
  ctx.save();
  ctx.clip(lp.box);
  ctx.fill(lp.h, "evenodd");
  ctx.restore();
}

function goldStroke(ctx: CanvasRenderingContext2D, draw: () => void, color: string, glow: string | null, w: number) {
  ctx.lineCap = "round";
  ctx.lineJoin = "round";
  if (glow) {
    ctx.beginPath();
    draw();
    ctx.strokeStyle = glow;
    ctx.lineWidth = w * 4;
    ctx.stroke();
  }
  ctx.beginPath();
  draw();
  ctx.strokeStyle = color;
  ctx.lineWidth = w;
  ctx.stroke();
}

// ---- the map ------------------------------------------------------------------------------------------------

export function drawMap(ctx: CanvasRenderingContext2D, W: number, H: number, spec: MapSpec) {
  const pal = PALETTES[spec.palette ?? "gold"];
  const s = spec.scale ?? Math.min(W, H) / 1080;
  const portrait = H > W;
  const pr = projector(spec, W, H);
  const draw = spec.draw ?? 1;
  const landA = spec.land ?? clamp01(draw * 1.6);
  ctx.save();
  ctx.clearRect(0, 0, W, H);
  if ((spec.ground ?? !!pal.ground) && pal.ground) {
    const g = ctx.createRadialGradient(W * 0.5, H * 0.6, 0, W * 0.5, H * 0.6, Math.hypot(W, H) * 0.62);
    g.addColorStop(0, pal.ground[0]);
    g.addColorStop(0.7, pal.ground[1]);
    g.addColorStop(1, pal.ground[2]);
    ctx.fillStyle = g;
    ctx.fillRect(0, 0, W, H);
  }
  const lp = landPath(pr);
  if (landA > 0) {
    ctx.globalAlpha = landA;
    fillLand(ctx, lp, W, H, pal.land);
    ctx.globalAlpha = 1;
  }
  if (spec.light && spec.light.r > 0) {
    const [lx, ly] = pr.xy(placeLL(spec.light.at));
    const R = Math.max(1, spec.light.r * Math.hypot(W, H) * 1.25);
    const lg = ctx.createRadialGradient(lx, ly, 0, lx, ly, R);
    lg.addColorStop(0, pal.light[0]);
    lg.addColorStop(0.3, pal.light[1]);
    lg.addColorStop(0.75, pal.light[2]);
    lg.addColorStop(1, "rgba(0,0,0,0)");
    fillLand(ctx, lp, W, H, lg);
    const halo = ctx.createRadialGradient(lx, ly, 0, lx, ly, R);
    halo.addColorStop(0, "rgba(255,230,176,0.3)");
    halo.addColorStop(1, "rgba(255,230,176,0)");
    ctx.fillStyle = halo;
    ctx.fillRect(0, 0, W, H);
    for (let i = 0; i < 3; i++) {
      ctx.beginPath();
      ctx.arc(lx, ly, R * (0.55 + 0.22 * i), 0, Math.PI * 2);
      ctx.strokeStyle = `rgba(255,226,160,${0.35 * (1 - i * 0.3) * clamp01(spec.light.r * 3)})`;
      ctx.lineWidth = 2 * s;
      ctx.stroke();
    }
  }
  // lakes: water-coloured fill, gold edge
  if (draw > 0) {
    ctx.globalAlpha = landA;
    LAKES.forEach((l) => {
      const path = new Path2D();
      ringPath(path, l.pts, pr);
      ctx.fillStyle = pal.lake;
      ctx.fill(path);
    });
    ctx.globalAlpha = 1;
    const skip = pr.hi ? inBox : undefined;
    goldStroke(ctx, () => {
      (pr.hi ? COAST_H : []).forEach((c) => trace(ctx, c, pr, draw));
      COAST_M.forEach((c) => trace(ctx, c, pr, draw, skip));
      LAKES.forEach((l) => trace(ctx, [...l.pts, l.pts[0], l.pts[1]], pr, draw));
    }, pal.coast, pal.glow, 1.6 * s);
    const rp = spec.rivers ?? draw;
    if (rp > 0) {
      // Rivers thin out on wide views so they never read as borders.
      const rw = Math.max(0.7, Math.min(1.8, 4 / spec.view.span)) * s;
      goldStroke(ctx, () => RIVERS.forEach((r) => (!spec.riverNames || spec.riverNames.includes(r.name)) && trace(ctx, r.pts, pr, rp)), pal.river, null, rw);
    }
  }
  // routes
  for (const r of spec.routes ?? []) {
    if (r.p <= 0) continue;
    const pts = routeFlat(r);
    const w = (r.width ?? 3) * s;
    if (r.faint) {
      ctx.save();
      ctx.setLineDash([5 * s, 7 * s]);
      ctx.globalAlpha = clamp01(r.p * 2);
      ctx.beginPath();
      trace(ctx, pts, pr, 1);
      ctx.strokeStyle = r.color ?? pal.faint;
      ctx.lineWidth = 1.6 * s;
      ctx.stroke();
      ctx.restore();
      continue;
    }
    let tip: { tip: [number, number] | null; ang: number } = { tip: null, ang: 0 };
    goldStroke(ctx, () => (tip = trace(ctx, pts, pr, r.p)), r.color ?? pal.route, pal.glow.replace(/[\d.]+\)$/, "0.32)"), w);
    if (r.arrow && tip.tip && r.p < 1) {
      const [x, y] = tip.tip;
      const a = tip.ang, L = 14 * s;
      ctx.beginPath();
      ctx.moveTo(x + Math.cos(a) * L * 0.6, y + Math.sin(a) * L * 0.6);
      ctx.lineTo(x + Math.cos(a + 2.5) * L, y + Math.sin(a + 2.5) * L);
      ctx.lineTo(x + Math.cos(a - 2.5) * L, y + Math.sin(a - 2.5) * L);
      ctx.closePath();
      ctx.fillStyle = r.color ?? pal.route;
      ctx.fill();
    }
  }
  // traveller marker
  if (spec.head && spec.head.a > 0) {
    const [x, y] = pr.xy(placeLL(spec.head.at));
    const pulse = 1 + 0.15 * Math.sin((spec.frame ?? 0) * 0.2);
    ctx.globalAlpha = clamp01(spec.head.a);
    ctx.beginPath();
    ctx.arc(x, y, (portrait ? 18 : 16) * s * pulse, 0, Math.PI * 2);
    ctx.fillStyle = spec.palette === "ink" ? "rgba(142,36,24,0.25)" : "rgba(255,226,160,0.25)";
    ctx.fill();
    ctx.beginPath();
    ctx.arc(x, y, (portrait ? 7 : 6) * s, 0, Math.PI * 2);
    ctx.fillStyle = spec.palette === "ink" ? pal.route : "#FFF6DC";
    ctx.fill();
    ctx.globalAlpha = 1;
  }
  // pins and labels
  const fs = (portrait ? 26 : 22) * s;
  for (const pin of spec.pins ?? []) {
    if (pin.a <= 0.001) continue;
    const place = typeof pin.at === "string" ? PLACES[pin.at] : undefined;
    const kind = pin.kind ?? place?.kind ?? "city";
    const [x, y] = pr.xy(placeLL(pin.at));
    const text = pin.label === false ? "" : pin.label ?? place?.name ?? "";
    ctx.globalAlpha = clamp01(pin.a);
    ctx.textAlign = "center";
    ctx.textBaseline = "alphabetic";
    if (kind === "region" || kind === "sea" || kind === "river") {
      const size = fs * (kind === "region" ? 1.25 : 1.05) * (pin.big ? 1.3 : 1);
      ctx.font = kind === "region" ? `600 ${size}px ${MAP_FONT.display}` : `italic 600 ${size}px ${MAP_FONT.serif}`;
      ctx.letterSpacing = `${(kind === "region" ? 0.42 : 0.16) * size}px`;
      ctx.fillStyle = kind === "region" ? pal.region : pal.sea;
      ctx.fillText(kind === "region" ? text.toUpperCase() : text, x + (pin.dx ?? 0) * s, y + (pin.dy ?? 0) * s);
      ctx.letterSpacing = "0px";
      ctx.globalAlpha = 1;
      continue;
    }
    ctx.beginPath();
    ctx.arc(x, y, (portrait ? 7 : 6) * s, 0, Math.PI * 2);
    ctx.fillStyle = pal.pin;
    ctx.fill();
    ctx.beginPath();
    ctx.arc(x, y, (portrait ? 16 : 14) * s, 0, Math.PI * 2);
    ctx.strokeStyle = pal.ring;
    ctx.globalAlpha = clamp01(pin.a) * 0.7;
    ctx.lineWidth = 1.5 * s;
    ctx.stroke();
    ctx.globalAlpha = clamp01(pin.a);
    if (text) {
      const size = pin.big ? fs * 1.2 : fs;
      ctx.font = `700 ${size}px ${MAP_FONT.display}`;
      ctx.letterSpacing = `${0.18 * size}px`;
      const tx = x + (pin.dx ?? 0) * s, ty = y + (pin.dy ?? -(portrait ? 28 : 24)) * s;
      if (pal.edge) {
        ctx.strokeStyle = pal.edge;
        ctx.lineWidth = 5 * s;
        ctx.lineJoin = "round";
        ctx.strokeText(text, tx, ty);
      }
      ctx.fillStyle = pal.label;
      ctx.fillText(text, tx, ty);
      ctx.letterSpacing = "0px";
    }
    ctx.globalAlpha = 1;
  }
  ctx.restore();
}
