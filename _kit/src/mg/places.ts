export const placeLL = (at: string | LL): LL => {
  if (typeof at !== "string") return at;
  const pl = PLACES[at];
  if (!pl) throw new Error(`unknown place "${at}" (add it to mg/places.ts or pass [lon, lat])`);
  return pl.ll;
};
